const DEFAULT_NAMES = new Set(['Untitled Project', '未命名项目']);

let lang = detectLanguage();
const listeners = new Set();

function detectLanguage() {
    const saved = localStorage.getItem('ve.lang');
    if (saved === 'zh' || saved === 'en') return saved;
    return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function getLanguage() {
    return lang;
}

export function t(key, vars = {}) {
    const pack = PACKS[lang] || PACKS.en;
    const fallback = PACKS.en;
    let text = lookup(pack, key);
    if (text === undefined) text = lookup(fallback, key);
    if (text === undefined) return key;
    return fill(text, vars);
}

function lookup(pack, key) {
    if (Object.prototype.hasOwnProperty.call(pack, key)) return pack[key];
    if (key.startsWith('err.')) return pack.err?.[key.slice(4)];
    return undefined;
}

function fill(text, vars) {
    return String(text).replace(/\{(\w+)\}/g, (match, name) => (
        Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
    ));
}

export function translateMessage(message) {
    const raw = String(message || '').trim();
    if (!raw) return '';
    if (lookup(PACKS[lang], raw) !== undefined || raw.startsWith('err.')) return t(raw);
    const key = SERVER[raw];
    return key ? t(key) : raw;
}

export function isDefaultProjectName(name) {
    return DEFAULT_NAMES.has(String(name || '').trim());
}

export function onLanguage(listener) {
    listeners.add(listener);
}

export function initI18n() {
    applyLanguage(false);
}

export function setLanguage(next) {
    lang = next === 'zh' ? 'zh' : 'en';
    localStorage.setItem('ve.lang', lang);
    applyLanguage(true);
}

function applyLanguage(notify) {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    document.title = t('appName');
    document.querySelectorAll('[data-i18n]').forEach((element) => {
        element.textContent = t(element.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-html]').forEach((element) => {
        element.innerHTML = t(element.dataset.i18nHtml);
    });
    document.querySelectorAll('[data-i18n-title]').forEach((element) => {
        element.title = t(element.dataset.i18nTitle);
    });
    document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
        element.setAttribute('aria-label', t(element.dataset.i18nAria));
    });
    document.querySelectorAll('[data-lang]').forEach((element) => {
        const active = element.dataset.lang === lang;
        element.classList.toggle('active', active);
        element.setAttribute('aria-pressed', active ? 'true' : 'false');
    });
    if (notify) listeners.forEach((listener) => listener(lang));
}
